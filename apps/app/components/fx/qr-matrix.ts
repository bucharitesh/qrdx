// Decorative QR tiles: 29 modules (version 3), finder patterns in three corners.
export const TILE = 29;
function finder(x: number, y: number): boolean | null {
  const inBox = (bx: number, by: number) => {
    const dx = x - bx;
    const dy = y - by;
    if (dx < -1 || dx > 7 || dy < -1 || dy > 7) return null;
    if (dx === -1 || dx === 7 || dy === -1 || dy === 7) return false;
    const ring = Math.min(dx, dy, 6 - dx, 6 - dy);
    return ring !== 1;
  };
  return inBox(1, 1) ?? inBox(TILE - 8, 1) ?? inBox(1, TILE - 8);
}

/** A decorative field of QR-like tiles: is module (x, y) dark? */
export function tiledModule(x: number, y: number): boolean {
  const tx = Math.floor(x / TILE);
  const ty = Math.floor(y / TILE);
  const lx = x - tx * TILE;
  const ly = y - ty * TILE;
  // Gutters between tiles.
  if (lx === 0 || ly === 0) return false;
  const f = finder(lx, ly);
  if (f !== null) return f;
  if (ly === 7 && lx > 8 && lx < TILE - 9) return lx % 2 === 1;
  if (lx === 7 && ly > 8 && ly < TILE - 9) return ly % 2 === 1;
  return hash2(x * 7 + 3, y * 13 + 1) > 0.52;
}

/** Is (x, y) part of a finder pattern (or its separator) in the tiled field? */
export function tiledFinder(x: number, y: number): boolean {
  const lx = x - Math.floor(x / TILE) * TILE;
  const ly = y - Math.floor(y / TILE) * TILE;
  return finder(lx, ly) !== null;
}
