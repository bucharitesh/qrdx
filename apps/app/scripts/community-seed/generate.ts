// Writes packages/database/scripts/community-seed-presets.json: the built-in
// themes the community seed publishes as official @qrdx themes
// (./preset-themes.ts). Run after changing one of those presets in
// utils/qr-presets.ts or a description:
//
//   cd apps/app && bun x tsx scripts/community-seed/generate.ts
//
// tests/database/seed-community.test.ts fails while the file is stale. It
// only reads the presets and writes the file: nothing connects to a
// database. Items already seeded never change (published versions are
// immutable), so an edit here only reaches a theme that isn't seeded yet.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildPresetSeedThemes } from "./preset-themes";

const root = join(__dirname, "..", "..");
const OUT = join(
  root,
  "..",
  "..",
  "packages",
  "database",
  "scripts",
  "community-seed-presets.json",
);
const ultracitePath = join(
  root,
  "..",
  "..",
  "node_modules",
  ".bin",
  "ultracite",
);

const themes = buildPresetSeedThemes();
const file = {
  note: "Generated by apps/app/scripts/community-seed/generate.ts from apps/app/utils/qr-presets.ts. Don't edit by hand.",
  themes,
};
writeFileSync(OUT, `${JSON.stringify(file, null, 2)}\n`);

// Keep the file as `ultracite check` expects it.
const fixed = spawnSync(ultracitePath, ["fix", OUT], {
  cwd: root,
  stdio: "inherit",
});
if (fixed.status !== 0) {
  throw new Error("ultracite fix failed on community-seed-presets.json");
}
console.log(`Wrote ${themes.length} themes to ${OUT}`);
