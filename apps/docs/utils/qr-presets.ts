/** Two- or more-stop linear gradient, stops spread evenly. */
const linear = (angle: number, ...colors: string[]): ColorConfig => ({
  type: "linear",
  angle,
  stops: colors.map((color, index) => ({
    color,
    offset: Math.round((index / (colors.length - 1)) * 100),
  })),
});

/** Radial gradient from the center out, stops spread evenly. */
const radial = (...colors: string[]): ColorConfig => ({
  type: "radial",
  stops: colors.map((color, index) => ({
    color,
    offset: Math.round((index / (colors.length - 1)) * 100),
  })),
});

