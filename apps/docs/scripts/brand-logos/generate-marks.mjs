// Writes lib/brand-logos/marks.generated.ts: the few brand marks the app's
// own UI draws (social icons, content types, share buttons), copied from the
// pinned simple-icons package so client bundles never import the whole set.
// The gallery loads every brand on demand from /api/brand-logos instead.
//
// Run after changing UI_SLUGS or upgrading simple-icons:
//   node scripts/brand-logos/generate-marks.mjs
// tests/brand-logos/marks.test.ts fails while the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import * as icons from "simple-icons";

/** Brands the app's UI shows. Sorted; add a slug, then run this script. */
export const UI_SLUGS = [
  "apple",
  "behance",
  "bitcoin",
  "bluesky",
  "caldotcom",
  "discord",
  "dribbble",
  "ethereum",
  "etsy",
  "facebook",
  "figma",
  "github",
  "google",
  "googledrive",
  "googleplay",
  "instagram",
  "paypal",
  "pinterest",
  "reddit",
  "snapchat",
  "soundcloud",
  "spotify",
  "telegram",
  "threads",
  "tiktok",
  "twitch",
  "venmo",
  "whatsapp",
  "x",
  "youtube",
];

const require = createRequire(import.meta.url);
// package.json isn't in the package's exports: read it next to its entry.
const pkg = JSON.parse(
  readFileSync(
    join(dirname(require.resolve("simple-icons")), "package.json"),
    "utf8",
  ),
);

const HEADER = `// Generated by scripts/brand-logos/generate-marks.mjs from simple-icons@${pkg.version}.
// Don't edit by hand: change UI_SLUGS there and run it again.
//
// Brand data from Simple Icons (https://simpleicons.org), CC0-1.0. The marks
// themselves are trademarks of their owners.
`;

/**
 * The release and its size, kept apart from the marks so light modules
 * (lib/product-facts.ts) can quote the count without shipping any paths.
 */
export function generateCatalog() {
  return `${HEADER}
/** The simple-icons release every brand mark comes from. */
export const SIMPLE_ICONS_VERSION = ${JSON.stringify(pkg.version)};

/** How many brands that release has (the gallery offers all of them). */
export const BRAND_LOGO_COUNT = ${Object.keys(icons).length};
`;
}

/** The marks module's source, from the installed simple-icons. */
export function generateMarks() {
  const bySlug = new Map(Object.values(icons).map((icon) => [icon.slug, icon]));
  const lines = UI_SLUGS.map((slug) => {
    const icon = bySlug.get(slug);
    if (!icon) throw new Error(`simple-icons has no "${slug}"`);
    return `  ${slug}: {\n    title: ${JSON.stringify(icon.title)},\n    hex: ${JSON.stringify(icon.hex)},\n    path: ${JSON.stringify(icon.path)},\n  },`;
  });
  return `${HEADER}
export {
  BRAND_LOGO_COUNT,
  SIMPLE_ICONS_VERSION,
} from "./catalog.generated";

/** Marks the app's own UI draws, by Simple Icons slug. */
export const BRAND_MARKS = {
${lines.join("\n")}
} as const;

export type BrandMarkSlug = keyof typeof BRAND_MARKS;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = join(import.meta.dirname, "../../lib/brand-logos");
  writeFileSync(join(dir, "catalog.generated.ts"), generateCatalog());
  writeFileSync(join(dir, "marks.generated.ts"), generateMarks());
  console.log(
    `wrote ${dir}/{catalog,marks}.generated.ts (${UI_SLUGS.length} marks)`,
  );
}
