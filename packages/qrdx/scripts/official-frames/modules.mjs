// Writes the modules that load the official frames from
// src/frames/official/*.json, in catalogue order (the hand-made frames,
// then catalogue.mjs):
//   src/frames/catalogue/all.ts           every frame (OFFICIAL_FRAMES)
//   src/frames/catalogue/<collection>.ts  one collection each, for loading a
//                                         picker's frames a group at a time
//   src/frames/catalogue/index.ts         id, name, collection, tags and a
//                                         spec hash per frame, no specs
//   src/frames/catalogue/counts.ts        counts
//   src/frames/catalogue/tags.ts          every tag, sorted
// Run through write.mjs.
