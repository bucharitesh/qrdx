/** JSON with object keys sorted. */
const stableJson = (value) => {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(",")}]`;
  if (value && typeof value === "object") {
    const keys = Object.keys(value)
      .filter((key) => value[key] !== undefined)
      .sort();
    return `{${keys.map((key) => `${JSON.stringify(key)}:${stableJson(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
};

/** FNV-1a (32-bit) of a spec's sorted-key JSON, as src/frames/spec-hash.ts. */
export function specHash(spec) {
  const text = stableJson(spec);
  let hash = 0x81_1c_9d_c5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01_00_01_93) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

const root = new URL("../../src/frames/", import.meta.url);
const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const HEADER =
  "// Generated by scripts/official-frames/write.mjs from src/frames/official/*.json.\n// Do not edit: change the frame files or the generator, then run it again.\n";

export function writeModules({ check = false } = {}) {
  const dir = fileURLToPath(new URL("official/", root));
  const files = readdirSync(dir).filter((file) => file.endsWith(".json"));
  const order = [...HAND_MADE, ...ENTRIES.map((entry) => entry.id)];
  const extra = files
    .map((file) => file.replace(/\.json$/, ""))
    .filter((id) => !order.includes(id));
  if (extra.length > 0)
    throw new Error(
      `Frames missing from the catalogue order: ${extra.join(", ")}`
    );
  const frames = order.map((id) => {
    const frame = JSON.parse(readFileSync(`${dir}${id}.json`, "utf8"));
    if (frame.id !== id) throw new Error(`${id}.json has id ${frame.id}`);
    if (!COLLECTIONS.includes(frame.collection))
      throw new Error(`${id}: unknown collection ${frame.collection}`);
    return frame;
  });

  const out = new Map();
  // Sorted by path, as biome sorts imports
  const imports = (list, from) =>
    [...list]
      .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
      .map(
        (frame) => `import ${camel(frame.id)} from "${from}${frame.id}.json";`
      )
      .join("\n");
  const array = (list) =>
    `[\n${list.map((frame) => `  ${camel(frame.id)},`).join("\n")}\n]`;

  out.set(
    "catalogue/all.ts",
    `${HEADER}import type { OfficialFrame } from "../official";\n${imports(frames, "../official/")}\n\n/** Every official frame, in catalogue order. */\n// A plain array literal (no call), so bundlers drop it when it's unused.\nexport const OFFICIAL_FRAME_LIST = ${array(frames)} as unknown as readonly OfficialFrame[];\n`
  );
  for (const collection of COLLECTIONS) {
    const list = frames.filter((frame) => frame.collection === collection);
    out.set(
      `catalogue/${collection}.ts`,
      `${HEADER}import type { OfficialFrame } from "../official";\n${imports(list, "../official/")}\n\n/** The official frames in the "${collection}" collection. */\nconst frames = ${array(list)} as unknown as readonly OfficialFrame[];\n\nexport default frames;\n`
    );
  }
  const index = frames.map((frame) => {
    const { width, height } = frame.spec.artboard;
    return {
      id: frame.id,
      name: frame.name,
      collection: frame.collection,
      ...(frame.occasion ? { occasion: frame.occasion } : {}),
      tags: frame.tags,
      hash: specHash(frame.spec),
      ratio: Math.round((width / height) * 1000) / 1000,
    };
  });
  out.set(
    "catalogue/index.ts",
    `${HEADER}import type { OfficialFrameIndexEntry } from "../official-types";\n\n/** Every official frame without its spec: for pickers and search. */\nexport const OFFICIAL_FRAME_INDEX: readonly OfficialFrameIndexEntry[] = ${JSON.stringify(index, null, 2)};\n`
  );
  const counts = Object.fromEntries(
    COLLECTIONS.map((collection) => [
      collection,
      frames.filter((frame) => frame.collection === collection).length,
    ])
  );
  const tags = [...new Set(frames.flatMap((frame) => frame.tags))].sort();
  out.set(
    "catalogue/counts.ts",
    `${HEADER}\n/** How many official frames there are. */\nexport const OFFICIAL_FRAME_COUNT = ${frames.length};\n\n/** Official frames per collection. */\nexport const OFFICIAL_FRAME_COUNTS = ${JSON.stringify(counts, null, 2)} as const;\n`
  );
  out.set(
    "catalogue/tags.ts",
    `${HEADER}\n/** Every tag an official frame carries, sorted. */\nexport const OFFICIAL_FRAME_TAGS: readonly string[] = ${JSON.stringify(tags, null, 2)};\n`
  );

  const stale = [];
  for (const [name, text] of out) {
    const file = fileURLToPath(new URL(name, root));
    let before = null;
    try {
      before = readFileSync(file, "utf8");
    } catch {
      // New module
    }
    // Ignore formatting (biome rewrites the files): compare without spaces
    const squash = (value) =>
      value
        ?.replace(/\s+/g, "")
        .replace(/,([\]}])/g, "$1")
        .replace(/"([a-zA-Z]\w*)":/g, "$1:");
    if (before === null || squash(before) !== squash(text)) {
      stale.push(name);
      if (!check) writeFileSync(file, text);
    }
  }
  return stale;
}
