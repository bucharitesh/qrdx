// Relations (for `database.query.*` with `with`); no effect on SQL.

export const organizationRelations = relations(organization, ({ many }) => ({
  members: many(member),
  invitations: many(invitation),
  qrCodes: many(qrCode),
  customDomains: many(customDomain),
  brandKits: many(brandKit),
}));

export const memberRelations = relations(member, ({ one }) => ({
  organization: one(organization, {
    fields: [member.organizationId],
    references: [organization.id],
  }),
  user: one(user, { fields: [member.userId], references: [user.id] }),
}));

export const invitationRelations = relations(invitation, ({ one }) => ({
  organization: one(organization, {
    fields: [invitation.organizationId],
    references: [organization.id],
  }),
  inviter: one(user, { fields: [invitation.inviterId], references: [user.id] }),
}));

export const customDomainRelations = relations(
  customDomain,
  ({ one, many }) => ({
    user: one(user, { fields: [customDomain.userId], references: [user.id] }),
    organization: one(organization, {
      fields: [customDomain.organizationId],
      references: [organization.id],
    }),
    qrCodes: many(qrCode),
  })
);

export const qrCodeRelations = relations(qrCode, ({ one, many }) => ({
  user: one(user, { fields: [qrCode.userId], references: [user.id] }),
  organization: one(organization, {
    fields: [qrCode.organizationId],
    references: [organization.id],
  }),
  domain: one(customDomain, {
    fields: [qrCode.domainId],
    references: [customDomain.id],
  }),
  scans: many(qrScan),
}));

export const qrScanRelations = relations(qrScan, ({ one }) => ({
  qrCode: one(qrCode, { fields: [qrScan.qrCodeId], references: [qrCode.id] }),
}));

export const brandKitRelations = relations(brandKit, ({ one }) => ({
  user: one(user, { fields: [brandKit.userId], references: [user.id] }),
  organization: one(organization, {
    fields: [brandKit.organizationId],
    references: [organization.id],
  }),
}));
