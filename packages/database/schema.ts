/** Dynamic QR codes: the printed QR encodes a short link that redirects here. */
export const qrCode = pgTable(
  "qr_code",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    organizationId: text("organization_id").references(() => organization.id, {
      onDelete: "set null",
    }),
    // Generated (7 base62 characters) or a custom back-half (3–64 of
    // [A-Za-z0-9_-]), case-sensitive. Unique per slug_scope, and per domain
    // (the two unique indexes below, from manual-sql/0009). The old global
    // unique constraint was dropped by manual-sql/0010 on 2 Nov 2026.
    slug: text("slug").notNull(),
    // Namespace of the slug: '' = shared (qrdx.dev/q/<slug>: generated slugs
    // and back-halves chosen on the default link), else the custom_domain id
    // a back-half was chosen on (only https://<domain>/<slug>). Plain text,
    // no FK: lib/slug-claims releaseDomainSlugs() empties it before a domain
    // is deleted.
    slugScope: text("slug_scope").notNull().default(""),
    destinationUrl: text("destination_url").notNull(),
    title: text("title"),
    contentType: text("content_type").notNull().default("url"),
    // Snapshot of the QR design used to render the code
    style: json("style").$type<ThemeStyles>(),
    domainId: text("domain_id").references(() => customDomain.id, {
      onDelete: "set null",
    }),
    // false only when an admin disables the code; plan downgrades never touch it
    isActive: boolean("is_active").notNull().default(true),
    archivedAt: timestamp("archived_at"),
    scanCount: integer("scan_count").notNull().default(0),
    lastScannedAt: timestamp("last_scanned_at"),
    kind: text("kind", { enum: QR_CODE_KINDS }).notNull().default("redirect"),
    // Hosted landing page shown when kind = 'page'
    pageId: text("page_id").references(() => landingPage.id, {
      onDelete: "set null",
    }),
    folderId: text("folder_id").references(() => folder.id, {
      onDelete: "set null",
    }),
    notes: text("notes"),
    isFavorite: boolean("is_favorite").notNull().default(false),
    // Lifecycle (lib/redirect/lifecycle.ts): password gate, schedule, scan cap, pause
    passwordHash: text("password_hash"),
    startsAt: timestamp("starts_at"),
    expiresAt: timestamp("expires_at"),
    scanLimit: integer("scan_limit"),
    pausedAt: timestamp("paused_at"),
    // Where ended (expired, paused, over the scan limit) codes send visitors
    fallbackUrl: text("fallback_url"),
    // Validated by the app (lib/redirect/*) on read and write
    routing: json("routing").$type<unknown>(),
    utm: json("utm").$type<unknown>(),
    pixels: json("pixels").$type<unknown>(),
    // Moved to the trash (restorable)
    deletedAt: timestamp("deleted_at"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at")
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    index("qr_code_user_id_idx").on(table.userId),
    index("qr_code_organization_id_idx").on(table.organizationId),
    index("qr_code_domain_id_idx").on(table.domainId),
    index("qr_code_folder_id_idx").on(table.folderId),
    index("qr_code_page_id_idx").on(table.pageId),
    // A namespace holds each slug once (/q/<slug> on the shared host).
    uniqueIndex("qr_code_slug_scope_slug_unique").on(
      table.slugScope,
      table.slug
    ),
    // A custom domain serves each slug once (https://<domain>/<slug>).
    uniqueIndex("qr_code_domain_id_slug_unique").on(table.domainId, table.slug),
  ]
);

